using System.Text.Json;
using System.Text.Json.Nodes;
using SnakeVs.Core;

namespace SnakeVs.Core.Tests;

/// <summary>
/// The ranking rules exist twice: here (C#, used by the game) and in the server (src/SnakeVs.Api, Rust).
/// tests/fixtures/leaderboard.json holds the cases both must agree on, with the expected answers computed by this C#
/// code. This test fails when the C# rules change and the fixture was not regenerated; the Rust tests fail when the
/// server no longer matches the fixture.
///
/// Regenerate: SNAKEVS_UPDATE_FIXTURES=1 dotnet test tests/SnakeVs.Core.Tests --filter LeaderboardFixture
/// then: cd src/SnakeVs.Api && cargo test
/// </summary>
public class LeaderboardFixtureTests
{
    private static readonly string[] NameInputs =
    [
        "ana", "  zé   lagarto  ", "joão!!@#da_silva-2", "Ñandú.ç", "ABCDEFGHIJKLMNOP", "abcdefghijk lmno",
        "<script>", "", "   ", "@#$%&", "日本語", "straße", "é decomposed", "a b", "tab\tname",
        "😀smile", "x                    y", "Ünïcødé", "ñandu", "12345678901234", "a.b-c_d", "  -  ",
    ];

    private static readonly ScoreSubmission[] PlausibilityInputs =
    [
        new(GameMode.Endless, Difficulty.Normal, "T", 10, 1, 1, 30),
        new(GameMode.Endless, Difficulty.Normal, "T", 0, 0, 1, 30),
        new(GameMode.Endless, Difficulty.Normal, "T", 999_999, 3, 1, 300),
        new(GameMode.Endless, Difficulty.Normal, "T", 50, 5, 1, 3),
        new(GameMode.Endless, Difficulty.Normal, "T", 50, 5, 2, 300),
        new(GameMode.Endless, Difficulty.Easy, "T", 130, 1, 1, 10),
        new(GameMode.Endless, Difficulty.Easy, "T", 131, 1, 1, 10),
        new(GameMode.Endless, Difficulty.Hard, "T", 100_000, 600, 1, 100_000),
        new(GameMode.Endless, Difficulty.Hard, "T", 100, 601, 1, 100_000),
        new(GameMode.Levels, Difficulty.Normal, "T", 900, 20, 3, 900),
        new(GameMode.Levels, Difficulty.Normal, "T", 900, 20, 9, 900),
        new(GameMode.Levels, Difficulty.Normal, "T", 900, 20, 0, 900),
        new(GameMode.Levels, Difficulty.Hard, "T", 2340, 8, 2, 200),
        new(GameMode.Levels, Difficulty.Hard, "T", 2341, 8, 2, 200),
        new(GameMode.Levels, Difficulty.Hard, "T", int.MaxValue, int.MaxValue, 268_435_456, long.MaxValue),
        new(GameMode.Levels, Difficulty.Hard, "T", 1, int.MaxValue, int.MaxValue, long.MaxValue),
        new(GameMode.Levels, Difficulty.Easy, "T", 10, -1, 1, 30),
        new(GameMode.Levels, Difficulty.Easy, "T", 10, 1, 1, 0),
        new(GameMode.Versus, Difficulty.Normal, "T", 10, 1, 1, 30),
    ];

    private static string FixturePath
    {
        get
        {
            var dir = new DirectoryInfo(AppContext.BaseDirectory);
            while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "SnakeVs.sln"))) dir = dir.Parent;
            Assert.NotNull(dir);
            return Path.Combine(dir.FullName, "tests", "fixtures", "leaderboard.json");
        }
    }

    [Fact]
    public void Fixture_MatchesTheCSharpRules()
    {
        var expected = Build(realRuns: null);
        if (Environment.GetEnvironmentVariable("SNAKEVS_UPDATE_FIXTURES") == "1")
        {
            var full = Build(realRuns: AutoplayRuns());
            Directory.CreateDirectory(Path.GetDirectoryName(FixturePath)!);
            File.WriteAllText(FixturePath, full.ToJsonString(new JsonSerializerOptions { WriteIndented = true }) + "\n");
        }

        var actual = JsonNode.Parse(File.ReadAllText(FixturePath))!.AsObject();
        foreach (var section in new[] { "rules", "names", "plausibility" })
        {
            Assert.True(
                JsonNode.DeepEquals(expected[section], actual[section]),
                $"tests/fixtures/leaderboard.json is out of date ({section}). Regenerate it: SNAKEVS_UPDATE_FIXTURES=1 dotnet test tests/SnakeVs.Core.Tests --filter LeaderboardFixture, then make the server pass: cd src/SnakeVs.Api && cargo test");
        }
    }

    [Fact]
    public void Fixture_RealRuns_ArePlausible()
    {
        var runs = JsonNode.Parse(File.ReadAllText(FixturePath))!["realRuns"]!.AsArray();
        Assert.NotEmpty(runs);
        foreach (var r in runs)
        {
            var s = ToSubmission(r!);
            Assert.True(Leaderboard.IsPlausible(s), $"Real run rejected: {s}");
        }
    }

    private static JsonObject Build(JsonArray? realRuns)
    {
        var root = new JsonObject
        {
            ["_comment"] = "Generated by tests/SnakeVs.Core.Tests/LeaderboardFixtureTests.cs. Do not edit by hand.",
            ["rules"] = new JsonObject
            {
                ["boardWidth"] = Rules.BoardWidth,
                ["boardHeight"] = Rules.BoardHeight,
                ["applesPerLevel"] = Rules.ApplesPerLevel,
                ["endlessApplesPerSpeedStep"] = Rules.EndlessApplesPerSpeedStep,
                ["appleScore"] = Rules.AppleScore,
                ["appleScorePerLevel"] = Rules.AppleScorePerLevel,
                ["goldenScore"] = Rules.GoldenScore,
                ["powerUpScore"] = Rules.PowerUpScore,
                ["levelBonus"] = Rules.LevelBonus,
                ["nameMaxLength"] = Leaderboard.NameMaxLength,
                ["defaultTake"] = Leaderboard.DefaultTake,
                ["maxTake"] = Leaderboard.MaxTake,
            },
            ["names"] = new JsonArray(NameInputs.Select(n => (JsonNode)new JsonObject
            {
                ["raw"] = n,
                ["expected"] = Leaderboard.NormalizeName(n),
            }).ToArray()),
            ["plausibility"] = new JsonArray(PlausibilityInputs.Select(s => (JsonNode)ToJson(s, Leaderboard.IsPlausible(s))).ToArray()),
        };
        if (realRuns is not null) root["realRuns"] = realRuns;
        return root;
    }

    private static JsonObject ToJson(ScoreSubmission s, bool? expected)
    {
        var o = new JsonObject
        {
            ["mode"] = s.Mode.ToString(),
            ["difficulty"] = s.Difficulty.ToString(),
            ["score"] = s.Score,
            ["apples"] = s.Apples,
            ["level"] = s.Level,
            ["steps"] = s.Steps,
        };
        if (expected is { } e) o["expected"] = e;
        return o;
    }

    private static ScoreSubmission ToSubmission(JsonNode n) => new(
        Enum.Parse<GameMode>(n["mode"]!.GetValue<string>()),
        Enum.Parse<Difficulty>(n["difficulty"]!.GetValue<string>()),
        "RUN",
        n["score"]!.GetValue<int>(),
        n["apples"]!.GetValue<int>(),
        n["level"]!.GetValue<int>(),
        n["steps"]!.GetValue<long>());

    /// <summary>Final scores of real games played by the CPU: the server must accept every one of them.</summary>
    private static JsonArray AutoplayRuns()
    {
        var runs = new JsonArray();
        foreach (var (mode, difficulty) in new[]
                 {
                     (GameMode.Endless, Difficulty.Easy), (GameMode.Endless, Difficulty.Normal), (GameMode.Endless, Difficulty.Hard),
                     (GameMode.Levels, Difficulty.Easy), (GameMode.Levels, Difficulty.Normal), (GameMode.Levels, Difficulty.Hard),
                 })
        {
            for (var game = 0; game < 6; game++)
            {
                var s = new GameSession(mode, difficulty, seed: 700 + game);
                s.Player.IsAiControlled = true;
                s.Player.AiMistakeChance = 0.01;
                for (var frame = 0; frame < 15000; frame++)
                {
                    s.ClearEvents();
                    s.Update(16.7);
                    if (s.State == SessionState.LevelCleared) s.AdvanceLevel();
                    if (s.State == SessionState.GameOver) break;
                }

                var p = s.Player;
                if (p.Score > 0) runs.Add(ToJson(new ScoreSubmission(mode, difficulty, "RUN", p.Score, p.ApplesEaten, s.Level, s.StepCount), null));
            }
        }

        return runs;
    }
}
